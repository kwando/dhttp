package main

import (
	"fmt"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"strings"
)

// Export through DuckDB so column types (especially in Parquet) retain their
// native representation. Stage the result before sending headers: a query
// error must not turn into a partial successful download.
func (s *server) formattedQuery(w http.ResponseWriter, r *http.Request, st statement, format string) {
	options := map[string]string{
		"csv":     "FORMAT CSV, HEADER true",
		"ndjson":  "FORMAT JSON, ARRAY false",
		"parquet": "FORMAT PARQUET",
	}
	mediaType := map[string]string{
		"csv":     "text/csv; charset=utf-8",
		"ndjson":  "application/x-ndjson",
		"parquet": "application/vnd.apache.parquet",
	}
	dir, err := os.MkdirTemp("", "duckdb-http-query-*")
	if err != nil {
		http.Error(w, "cannot create export file", http.StatusInternalServerError)
		return
	}
	defer os.RemoveAll(dir)
	path := filepath.Join(dir, "result."+format)
	query := strings.TrimSpace(st.sql)
	query = strings.TrimSpace(strings.TrimSuffix(query, ";"))
	// The destination is generated by the server; query parameters stay bound
	// to the inner SELECT as they are for the regular JSON endpoint.
	sql := "COPY (" + query + ") TO '" + strings.ReplaceAll(path, "'", "''") + "' (" + options[format] + ")"
	if _, err := s.db.ExecContext(r.Context(), sql, st.args...); err != nil {
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}
	f, err := os.Open(path)
	if err != nil {
		http.Error(w, "export unavailable", http.StatusInternalServerError)
		return
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		http.Error(w, "export unavailable", http.StatusInternalServerError)
		return
	}
	w.Header().Set("Content-Type", mediaType[format])
	w.Header().Set("Content-Disposition", fmt.Sprintf(`attachment; filename="result.%s"`, format))
	w.Header().Set("Content-Length", fmt.Sprint(info.Size()))
	_, _ = io.Copy(w, f)
}
